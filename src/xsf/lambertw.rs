/// `xsf::lambertw(double, long, double)`: the real Lambert W function for `k = 0` and `k = -1`,
/// using the interval minimax approximations of \[5\]
fn lambertw_f64(z: f64, k: isize) -> f64 {
    #[allow(clippy::wildcard_imports)] // `using namespace detail::lambertw_real;`
    use lambertw_real::*;
    const X0: f64 = 0.606_530_659_712_633_4;

    // upper bounds of z for the minimax approximations in sqrt(z - z0) for k = 0
    const K0_SQRT: [(f64, &[f64], &[f64]); 17] = [
        (2.182_014_465_332_031_2, &P1, &Q1),
        (43.246_045_021_497_93, &P2, &Q2),
        (598.085_654_277_611_3, &P3, &Q3),
        (8_049.124_105_634_591, &P4, &Q4),
        (111_124.586_241_776_65, &P5, &Q5),
        (1_587_042.613_328_788_4, &P6, &Q6),
        (23_414_708.033_996_02, &P7, &Q7),
        (355_764_742.712_220_2, &P8, &Q8),
        (5_550_171_629.248_484, &P9, &Q9),
        (88_674_704_839.289_9, &P10, &Q10),
        (1_447_779_186_526.922_4, &P11, &Q11),
        (24_111_458_632_511.484, &P12, &Q12),
        (408_970_364_426_008.06, &P13, &Q13),
        (7_055_590_147_678_997.0, &P14, &Q14),
        (1.236_660_755_797_672_8e17, &P15, &Q15),
        (2.199_937_348_793_1e18, &P16, &Q16),
        (3.968_539_219_834_401_6e19, &P17, &Q17),
    ];
    // upper bounds of z for the minimax approximations in -z / (sqrt(z - z0) + x0) for k = -1
    const KM1_SQRT: [(f64, &[f64], &[f64]); 7] = [
        (-0.188_726_882_822_894_35, &PM1, &QM1),
        (-0.060_497_597_226_958_34, &PM2, &QM2),
        (-0.017_105_334_740_676_01, &PM3, &QM3),
        (-0.004_595_496_212_794_371, &PM4, &QM4),
        (-0.001_200_161_067_219_772_4, &PM5, &QM5),
        (-0.000_307_288_059_321_915, &PM6, &QM6),
        (-7.744_715_983_806_218e-5, &PM7, &QM7),
    ];
    // upper bounds of z for the minimax approximations in log(-z) for k = -1
    const KM1_LOG: [(f64, &[f64], &[f64]); 3] = [
        (-4.580_811_969_815_817_5e-17, &PM8, &QM8),
        (-6.107_367_223_659_479e-79, &PM9, &QM9),
        (0.0, &PM10, &QM10),
    ];

    // tol not used in this method
    if z.is_nan() || z < Z0 {
        return f64::NAN;
    }

    if k == 0 {
        if z.abs() < 0.055 {
            // empirically determined region around zero where 10 terms of the
            // series expansion is more accurate than the minimax approximation
            return lambertw_series(z);
        }
        for (zmax, p, q) in K0_SQRT {
            if z < zmax {
                return ratevl((z - Z0).sqrt(), p, q);
            }
        }
        if z < 1.412_707_514_527_465_2e104 {
            return ratevl(z.ln(), &P18, &Q18);
        }
        if z.is_finite() {
            return ratevl(z.ln(), &P19, &Q19);
        }
        f64::INFINITY
    } else if k == -1 {
        if z < -0.354_291_330_944_216_4 {
            return ratevl((z - Z0).sqrt(), &PM05, &QM05);
        }
        for (zmax, p, q) in KM1_SQRT {
            if z < zmax {
                return ratevl(-z / ((z - Z0).sqrt() + X0), p, q);
            }
        }
        for (zmax, p, q) in KM1_LOG {
            if z < zmax {
                return ratevl((-z).ln(), p, q);
            }
        }
        f64::NAN // z > 0
    } else {
        f64::NAN
    }
}

/// Lambert W function.
///
/// The Lambert W function `W(z)` is defined as the inverse function of `w * exp(w)`. In other
/// words, the value of `W(z)` is such that `z = W(z) * exp(W(z))` for any complex number `z`.
///
/// The Lambert W function is a multivalued function with infinitely many branches. Each branch
/// gives a separate solution of the equation `z = w exp(w)`. Here, the branches are indexed by the
/// integer `k`.
///
/// Corresponds to [`scipy.special.lambertw`][scipy].
///
/// [scipy]: https://docs.scipy.org/doc/scipy/reference/generated/scipy.special.lambertw.html
///
/// # See also
/// - [`wrightomega`](crate::wrightomega): Wright Omega function
#[doc(alias = "lambert_w")]
#[must_use]
#[allow(clippy::float_cmp, clippy::cast_precision_loss)]
pub fn lambertw(z: Complex<f64>, k: isize, tol: f64) -> Complex<f64> {
    if z.im == 0.0
        && ((k == 0 && z.re > lambertw_real::Z0)
            || (k == -1 && z.re > lambertw_real::Z0 && z.re < 0.0))
    {
        // shortcut and use the real-valued calculation
        return Complex::new(lambertw_f64(z.re, k), 0.0);
    }

    if z.is_nan() {
        return z;
    }
    if z.re == f64::INFINITY {
        return z + 2.0 * PI * k as f64 * Complex::I;
    }
    if z.re == f64::NEG_INFINITY {
        return -z + (2.0 * PI * k as f64 + PI) * Complex::I;
    }
    if z == Complex::ZERO {
        if k == 0 {
            return z;
        }
        return Complex::new(f64::NEG_INFINITY, 0.0);
    }
    if z == Complex::ONE && k == 0 {
        // Split out this case because the asymptotic series blows up
        return Complex::new(OMEGA, 0.0);
    }

    let absz = z.norm();
    // Get an initial guess for Halley's method
    let mut w = if k == 0 {
        if (z + EXPN1).norm() < 0.3 {
            lambertw_branchpt(z)
        } else if -1.0 < z.re && z.re < 1.5 && z.im.abs() < 1.0 && -2.5 * z.im.abs() - 0.2 < z.re {
            /* Empirically determined decision boundary where the Pade
             * approximation is more accurate. */
            lambertw_pade0(z)
        } else {
            lambertw_asy(z, k)
        }
    } else if k == -1 {
        if absz <= EXPN1 && z.im == 0.0 && z.re < 0.0 {
            Complex::new((-z.re).ln(), 0.0)
        } else {
            lambertw_asy(z, k)
        }
    } else {
        lambertw_asy(z, k)
    };

    // Halley's method; see 5.9 in [1]
    if w.re >= 0.0 {
        // Rearrange the formula to avoid overflow in exp
        for _ in 0..100 {
            let ew = (-w).exp();
            let wewz = w - z * ew;
            let wn = w - cdiv(wewz, w + 1.0 - cdiv((w + 2.0) * wewz, 2.0 * w + 2.0));
            if (wn - w).norm() <= tol * wn.norm() {
                return wn;
            }
            w = wn;
        }
    } else {
        for _ in 0..100 {
            let ew = w.exp();
            let wew = w * ew;
            let wewz = wew - z;
            let wn = w - cdiv(wewz, wew + ew - cdiv((w + 2.0) * wewz, 2.0 * w + 2.0));
            if (wn - w).norm() <= tol * wn.norm() {
                return wn;
            }
            w = wn;
        }
    }

    Complex::new(f64::NAN, f64::NAN)
}
