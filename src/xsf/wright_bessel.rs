    A[0] = 1.;
    B[0] = 1.;
    Ap1[0] = 1.;
    for k in 1..15 {
        A[k] = A[k - 1] * a;
    }
    for k in 1..17 {
        B[k] = B[k - 1] * b;
    }
    for k in 1..9 {
        Ap1[k] = Ap1[k - 1] * (1.0 + a);
    }

    C[0] = 1. / (TAU * Ap1[1]).sqrt();

    C[1] = C[0] / (24.0 * Ap1[1]);
    C[1] *= (2.0 * a + 1.0) * (2.0 + a) - 12.0 * b * (1.0 + a - b);

