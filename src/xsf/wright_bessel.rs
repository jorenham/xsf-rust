//! Finally they are put together in wright_bessel. See the docstring of
//! that function for more details.
//!
//! `set_error` is a no-op in our build of xsf, so the calls to it are omitted.
//!
//! In `wb_large_a`, the `int` arithmetic on `k_max` overflows for huge `x` (e.g. `x > 3e59` for
//! `a = 5`), which is undefined behavior in C++. Like the C++ (on x86-64), it wraps around here,
//! so that `wright_bessel` returns `0` and `log_wright_bessel` returns `-inf` in that case.
//!
//! Note that our `lanczos_sum_expg_scaled` uses fused multiply-adds, so `exp_rgamma` (and therefore
//! `wright_bessel` for `a == 0` or tiny `a`) can differ from xsf in the last bits.

#![allow(non_snake_case, clippy::if_not_else)]

use core::f64::consts::{FRAC_PI_2, PI, TAU};

use crate::xsf::cephes::polevl::polevl;
use crate::xsf::cephes::{LANCZOS_G, lanczos_sum_expg_scaled, lgam, rgamma, zeta};
use crate::xsf::trig::{cephes_cospi, cephes_sinpi};

// rgamma_zero: smallest value x for which rgamma(x) == 0 as x gets large
const RGAMMA_ZERO: f64 = 178.472_411_158_866_38;

fn exp_rgamma(x: f64, y: f64) -> f64 {
    /* Compute exp(x) / gamma(y) = exp(x) * rgamma(y).
     *
     * This helper function avoids overflow by using the lanczos
     * approximation of the gamma function.
     */
    (x + (1.0 - (y + LANCZOS_G - 0.5).ln()) * (y - 0.5)).exp() / lanczos_sum_expg_scaled(y)
}

#[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
fn wb_series(a: f64, b: f64, x: f64, nstart: u32, mut nstop: u32) -> f64 {
    /* 1. Taylor series expansion in x=0 for x <= 1.
     *
     * Phi(a, b, x) = sum_k x^k / k! / Gamma(a*k + b)
     *
     * Note that every term, and therefore also Phi(a, b, x) is
     * monotone decreasing with increasing a or b.
     */
    let mut xk_k = x.powf(f64::from(nstart)) * rgamma(f64::from(nstart + 1)); // x^k/k!
    let mut res = xk_k * rgamma(f64::from(nstart) * a + b);
    // term k=nstart+1, +2, +3, ...
    if nstop > nstart {
        // series expansion until term k such that a*k+b <= rgamma_zero
        let k_max = ((RGAMMA_ZERO - b) / a).floor() as u32;
        if nstop > k_max {
            nstop = k_max;
        }
        for k in nstart + 1..nstop {
            xk_k *= x / f64::from(k);
            res += xk_k * rgamma(a * f64::from(k) + b);
        }
    }
    res
}

#[allow(clippy::cast_possible_truncation)]
fn wb_large_a<const LOG_WB: bool>(a: f64, b: f64, x: f64, n: i32) -> f64 {
    /* 2. Taylor series expansion in x=0, for large a.
     *
     * Phi(a, b, x) = sum_k x^k / k! / Gamma(a*k + b)
     *
     * Use Stirling's formula to find k=k_max, the maximum term.
     * Then use n terms of Taylor series around k_max.
     */
    let k_max = (a.powf(-a) * x).powf(1.0 / (1.0 + a)) as i32;

    let mut nstart = k_max.wrapping_sub(n / 2);
    if nstart < 0 {
        nstart = 0;
    }

    let mut res = 0.0;
    let lnx = x.ln();
    // For numerical stability, we factor out the maximum term exp(..) with k=k_max
    // but only if it is larger than 0.
    let max_exponent = 0.0_f64.max(
        f64::from(k_max) * lnx
            - lgam(f64::from(k_max.wrapping_add(1)))
            - lgam(a * f64::from(k_max) + b),
    );
    for k in nstart..nstart.wrapping_add(n) {
        let k = f64::from(k);
        res += (k * lnx - lgam(k + 1.0) - lgam(a * k + b) - max_exponent).exp();
    }

    if !LOG_WB {
        res *= max_exponent.exp();
    } else {
        // logarithm of Wright's function
        res = max_exponent + res.ln();
    }
    res
}

#[allow(
    clippy::cast_precision_loss,
    clippy::items_after_statements,
    clippy::many_single_char_names,
    clippy::too_many_lines
)]
fn wb_small_a<const LOG_WB: bool>(a: f64, b: f64, x: f64, mut order: usize) -> f64 {
    /* 3. Taylor series in a=0 up to order 5, for tiny a and not too large x
    *
    * Phi(a, b, x) = exp(x)/Gamma(b)
                     * (1 - a*x * Psi(b) + a^2/2*x*(1+x) * (Psi(b)^2 - Psi'(b)
                        + ... )
                     + O(a^6))
    *
    * where Psi is the digamma function.
    *
    * Parameter order takes effect only when b > 1e-3 and 2 <= order <= 5,
    * otherwise it defaults to 2, or if b <= 1e-3, to 5. The lower order is,
    * the fewer polygamma functions have to be computed.
    *
    * Call: python _precompute/wright_bessel.py 1
    *
    * For small b, i.e. b <= 1e-3, cancellation of poles of digamma(b)/Gamma(b)
    * and polygamma needs to be carried out => series expansion in a=0 to order 5
    * and in b=0 to order 4.
    * Call: python _precompute/wright_bessel.py 2
    */
    let mut A = [0.0; 6]; // coefficients of a^k  (1, -x * Psi(b), ...)
    let mut B = [0.0; 6]; // powers of b^k/k! or terms in polygamma functions
    const C: [f64; 5] = [
        // coefficients of a^k1 * b^k2
        1.0,                      // C[0]
        1.154_431_329_803_065_7,  // C[1]
        -3.935_268_429_121_523_4, // C[2]
        -1.008_063_240_818_285_7, // C[3]
        19.984_633_365_874_98,    // C[4]
    ];
    let X = [
        // polynomials in x;
        1.0,                                                  // X[0]
        x,                                                    // X[1]
        x * (x + 1.0),                                        // X[2]
        x * (x * (x + 3.0) + 1.0),                            // X[3]
        x * (x * (x * (x + 6.0) + 7.0) + 1.0),                // X[4]
        x * (x * (x * (x * (x + 10.0) + 25.0) + 15.0) + 1.0), // X[5]
    ];
    let mut res;

    if b <= 1E-3 {
        /* Series expansion of both a and b up to order 5:
         * M_PI = pi
         * M_EG = Euler Gamma aka Euler Mascheroni constant
         * M_Z3 = zeta(3)
         * C[0] = 1
         * C[1] = 2*M_EG
         * C[2] = 3*M_EG^2 - M_PI^2/2
         * C[3] = 4*M_EG^3 - 2*M_EG*M_PI^2 + 8*M_Z3
         * C[4] = 5*M_EG^4 - 5*M_EG^2*M_PI^2 + 40*M_EG*M_Z3 + M_PI^4/12
         */
        B[0] = 1.;
        for k in 1..5 {
            B[k] = b / k as f64 * B[k - 1];
        }
        // Note that polevl assumes inverse ordering => A[5] = 0th term
        A[5] = rgamma(b);
        A[4] = X[1] * (C[0] + C[1] * b + C[2] * B[2] + C[3] * B[3] + C[4] * B[4]);
        A[3] = X[2] / 2. * (C[1] + C[2] * b + C[3] * B[2] + C[4] * B[3]);
        A[2] = X[3] / 6. * (C[2] + C[3] * b + C[4] * B[2]);
        A[1] = X[4] / 24. * (C[3] + C[4] * b);
        A[0] = X[5] / 120. * C[4];
        // res = exp(x) * (A[5] + A[4] * a + A[3] * a^2 + A[2] * a^3 + ...)
        if !LOG_WB {
            res = x.exp() * polevl(a, &A[..=5]);
        } else {
            // logarithm of Wright's function
            res = x + polevl(a, &A[..=5]).ln();
        }
    } else {
        /* Phi(a, b, x) = exp(x)/gamma(b) * sum(A[i] * X[i] * B[i], i=0..5)
         * A[n] = a^n/n!
         * But here, we repurpose A[n] = X[n] * B[n] / n!
         * Note that polevl assumes inverse ordering => A[order] = 0th term */
        let dg = crate::digamma(b);
        // pg1 = polygamma(1, b)
        let pg1 = zeta(2.0, b);
        if order <= 2 {
            res = 1.0 + a * x * (-dg + 0.5 * a * (1.0 + x) * (dg * dg - pg1));
        } else {
            if order > 5 {
                order = 5;
            }
            // pg2 = polygamma(2, b)
            let pg2 = -2.0 * zeta(3.0, b);
            B[0] = 1.0;
            B[1] = -dg;
            B[2] = dg * dg - pg1;
            B[3] = (-dg * dg + 3.0 * pg1) * dg - pg2;
            A[order] = 1.0;
            A[order - 1] = X[1] * B[1];
            A[order - 2] = X[2] * B[2] / 2.;
            A[order - 3] = X[3] * B[3] / 6.;
            if order >= 4 {
                // double pg3 = polygamma(3, b)
                let pg3 = 6.0 * zeta(4.0, b);
                B[4] = ((dg * dg - 6.0 * pg1) * dg + 4.0 * pg2) * dg + 3.0 * pg1 * pg1 - pg3;
                A[order - 4] = X[4] * B[4] / 24.;
                if order >= 5 {
                    // pg4 = polygamma(4, b)
                    let pg4 = -24.0 * zeta(5.0, b);
                    B[5] = (((-dg * dg + 10.0 * pg1) * dg - 10.0 * pg2) * dg - 15.0 * pg1 * pg1
                        + 5.0 * pg3)
                        * dg
                        + 10.0 * pg1 * pg2
                        - pg4;
                    A[order - 5] = X[5] * B[5] / 120.;
                }
            }
            res = polevl(a, &A[..=order]);
        }
        // res *= exp(x) * rgamma(b)
        if !LOG_WB {
            res *= exp_rgamma(x, b);
        } else {
            // logarithm of Wright's function
            res = x - lgam(b) + res.ln();
        }
    }
    res
}

