/// Compute
///
/// ```text
/// x^a * exp(-x) / gamma(a)
/// ```
///
/// corrected from (15) and (16) in \[2\] by replacing exp(x - a) with
/// exp(a - x).
pub(super) fn igam_fac(a: f64, x: f64) -> f64 {
    if (a - x).abs() > 0.4 * a.abs() {
        let ax = a * x.ln() - x - lgam(a);
        if ax < -MAXLOG {
            return 0.0;
        }
        return ax.exp();
    }

    let fac = a + LANCZOS_G - 0.5;
    let mut res = (fac / E).sqrt() / lanczos_sum_expg_scaled(a);

    if (a < 200.0) && (x < 200.0) {
        res *= (a - x).exp() * (x / fac).powf(a);
    } else {
        let num = x - a - LANCZOS_G + 0.5;
        res *= (a * log1pmx(num / fac) + x * (0.5 - LANCZOS_G) / fac).exp();
    }

    res
}

/// Compute igamc using DLMF 8.9.2.
#[allow(clippy::float_cmp, clippy::if_not_else)]
fn igamc_continued_fraction(a: f64, x: f64) -> f64 {
    let ax = igam_fac(a, x);
    if ax == 0.0 {
        return 0.0;
    }

    /* continued fraction */
    let mut y = 1.0 - a;
    let mut z = x + y + 1.0;
    let mut c = 0.0;
    let mut pkm2 = 1.0;
    let mut qkm2 = x;
    let mut pkm1 = x + 1.0;
    let mut qkm1 = z * x;
    let mut ans = pkm1 / qkm1;

    for _ in 0..IGAM_MAXITER {
        c += 1.0;
        y += 1.0;
        z += 2.0;
        let yc = y * c;
        let pk = pkm1 * z - pkm2 * yc;
        let qk = qkm1 * z - qkm2 * yc;
        let t = if qk != 0.0 {
            let r = pk / qk;
            let t = ((ans - r) / r).abs();
            ans = r;
            t
        } else {
            1.0
        };
        pkm2 = pkm1;
        pkm1 = pk;
        qkm2 = qkm1;
        qkm1 = qk;
        if pk.abs() > IGAM_BIG {
            pkm2 *= IGAM_BIGINV;
            pkm1 *= IGAM_BIGINV;
            qkm2 *= IGAM_BIGINV;
            qkm1 *= IGAM_BIGINV;
        }
        if t <= MACHEP {
            break;
        }
    }

    ans * ax
}

/// Compute igam using DLMF 8.11.4.
#[allow(clippy::float_cmp)]
fn igam_series(a: f64, x: f64) -> f64 {
    let ax = igam_fac(a, x);
    if ax == 0.0 {
        return 0.0;
    }

    /* power series */
    let mut r = a;
    let mut c = 1.0;
    let mut ans = 1.0;

    for _ in 0..IGAM_MAXITER {
        r += 1.0;
        c *= x / r;
        ans += c;
        if c <= MACHEP * ans {
            break;
        }
    }

    ans * ax / a
}

/// Compute igamc using DLMF 8.7.3. This is related to the series in
/// igam_series but extra care is taken to avoid cancellation.
fn igamc_series(a: f64, x: f64) -> f64 {
    let mut fac = 1.0;
    let mut sum = 0.0;

    for n in 1..IGAM_MAXITER {
        fac *= -x / f64::from(n);
        let term = fac / (a + f64::from(n));
        sum += term;
        if term.abs() <= MACHEP * sum.abs() {
            break;
        }
    }

    let logx = x.ln();
    let term = -(a * logx - lgam1p(a)).exp_m1();
    term - (a * logx - lgam(a)).exp() * sum
}

/// Compute igam/igamc using DLMF 8.12.3/8.12.4.
fn asymptotic_series(a: f64, x: f64, func: i32) -> f64 {
    let mut maxpow = 0;
    let lambda = x / a;
    let sigma = (x - a) / a;
    let mut absoldterm = f64::INFINITY;
    let mut etapow = [0.0; IGAM_ASYMP_COEFF_N];
    etapow[0] = 1.0;
    let mut sum = 0.0;
    let mut afac = 1.0;

    let sgn = if func == IGAM { -1.0 } else { 1.0 };

    let eta = if lambda > 1.0 {
        (-2.0 * log1pmx(sigma)).sqrt()
    } else if lambda < 1.0 {
        -(-2.0 * log1pmx(sigma)).sqrt()
    } else {
        0.0
    };
    let mut res = 0.5 * erfc(sgn * eta * (a / 2.0).sqrt());

    for d in &IGAM_ASYMP_COEFF_D {
        let mut ck = d[0];
        for n in 1..IGAM_ASYMP_COEFF_N {
            if n > maxpow {
                etapow[n] = eta * etapow[n - 1];
                maxpow += 1;
            }
            let ckterm = d[n] * etapow[n];
            ck += ckterm;
            if ckterm.abs() < MACHEP * ck.abs() {
                break;
            }
        }
        let term = ck * afac;
        let absterm = term.abs();
        if absterm > absoldterm {
            break;
        }
        sum += term;
        if absterm < MACHEP * sum.abs() {
            break;
        }
        absoldterm = absterm;
        afac /= a;
    }
    res += sgn * (-0.5 * a * eta * eta).exp() * sum / (TAU * a).sqrt();

    res
}

/// Incomplete Gamma integral
///
/// The function is defined by
///
/// ```text
///                           x
///                            -
///                   1       | |  -t  a-1
///  igam(a,x)  =   -----     |   e   t   dt.
///                  -      | |
///                 | (a)    -
///                           0
/// ```
///
/// In this implementation both arguments must be positive.
/// The integral is evaluated by either a power series or
/// continued fraction expansion, depending on the relative
/// values of a and x.
///
/// ACCURACY:
///
/// ```text
///                      Relative error:
/// arithmetic   domain     # trials      peak         rms
///    IEEE      0,30        20000       4.5e-14     3.7e-15
///    IEEE      0,100       20000       1.7e-13     2.0e-14
/// ```
///
/// Outputs smaller than the IEEE gradual underflow threshold
/// were excluded from these statistics.
#[allow(clippy::float_cmp, clippy::if_same_then_else)]
pub(crate) fn igam(a: f64, x: f64) -> f64 {
    if a.is_nan() || x.is_nan() {
        return f64::NAN;
    }

    if x < 0.0 || a < 0.0 {
        return f64::NAN;
    } else if a == 0.0 {
        if x > 0.0 {
            return 1.0;
        }
        return f64::NAN;
    } else if x == 0.0 {
        /* Zero integration limit */
        return 0.0;
    } else if a.is_infinite() {
        if x.is_infinite() {
            return f64::NAN;
        }
        return 0.0;
    } else if x.is_infinite() {
        return 1.0;
    }

    /* Asymptotic regime where a ~ x; see [2]. */
    let absxma_a = (x - a).abs() / a;
    if (a > IGAM_SMALL) && (a < IGAM_LARGE) && (absxma_a < IGAM_SMALLRATIO) {
        return asymptotic_series(a, x, IGAM);
    } else if (a > IGAM_LARGE) && (absxma_a < IGAM_LARGERATIO / a.sqrt()) {
        return asymptotic_series(a, x, IGAM);
    }

    if (x > 1.0) && (x > a) {
        return 1.0 - igamc(a, x);
    }

    igam_series(a, x)
}

/// Complemented incomplete Gamma integral
///
/// The function is defined by
///
/// ```text
///  igamc(a,x)   =   1 - igam(a,x)
///
///                            inf.
///                              -
///                     1       | |  -t  a-1
///               =   -----     |   e   t   dt.
///                    -      | |
///                   | (a)    -
///                             x
/// ```
///
/// In this implementation both arguments must be positive.
/// The integral is evaluated by either a power series or
/// continued fraction expansion, depending on the relative
/// values of a and x.
///
/// ACCURACY:
///
/// Tested at random a, x.
///
/// ```text
///                a         x                      Relative error:
/// arithmetic   domain   domain     # trials      peak         rms
///    IEEE     0.5,100   0,100       20000       1.1e-13     8.4e-15
///    IEEE     0.01,0.5  0,100       20000       1.5e-14     3.9e-15
/// ```
#[allow(clippy::float_cmp, clippy::if_same_then_else)]
pub(crate) fn igamc(a: f64, x: f64) -> f64 {
    if a.is_nan() || x.is_nan() {
        return f64::NAN;
    }

    if x < 0.0 || a < 0.0 {
        return f64::NAN;
    } else if a == 0.0 {
        if x > 0.0 {
            return 0.0;
        }
        return f64::NAN;
    } else if x == 0.0 {
        return 1.0;
    } else if a.is_infinite() {
        if x.is_infinite() {
            return f64::NAN;
        }
        return 1.0;
    } else if x.is_infinite() {
        return 0.0;
    }

    /* Asymptotic regime where a ~ x; see [2]. */
    let absxma_a = (x - a).abs() / a;
    if (a > IGAM_SMALL) && (a < IGAM_LARGE) && (absxma_a < IGAM_SMALLRATIO) {
        return asymptotic_series(a, x, IGAMC);
    } else if (a > IGAM_LARGE) && (absxma_a < IGAM_LARGERATIO / a.sqrt()) {
        return asymptotic_series(a, x, IGAMC);
    }

    /* Everywhere else; see [2]. */
    if x > 1.1 {
        if x < a {
            1.0 - igam_series(a, x)
        } else {
            igamc_continued_fraction(a, x)
        }
    } else if x <= 0.5 {
        if -0.4 / x.ln() < a {
            1.0 - igam_series(a, x)
        } else {
            igamc_series(a, x)
        }
    } else if x * 1.1 < a {
        1.0 - igam_series(a, x)
    } else {
        igamc_series(a, x)
    }
}
