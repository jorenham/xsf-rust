const MAXITER: u64 = 500;
const MACHEP: f64 = 1.110_223_024_625_156_5e-16; // 2**-53
const SCIPY_EULER: f64 = 0.577_215_664_901_532_9;

/*
 * Compute Iv from (AMS5 9.7.1), asymptotic expansion for large |z|
 * Iv ~ exp(x)/sqrt(2 pi x) ( 1 + (4*v*v-1)/8x + (4*v*v-1)(4*v*v-9)/8x/2! + ...)
 */
#[allow(clippy::neg_cmp_op_on_partial_ord)]
fn iv_asymptotic(v: f64, x: f64) -> f64 {
    let mut term;
    let mut factor;

    let prefactor = x.exp() / (2.0 * PI * x).sqrt();

    if prefactor == f64::INFINITY {
        return prefactor;
    }

    let mu = 4.0 * v * v;
    let mut sum = 1.0;
    term = 1.0;
    let mut k: i32 = 1;

    loop {
        factor = (mu - f64::from((2 * k - 1) * (2 * k - 1))) / (8.0 * x) / f64::from(k);
        if k > 100 {
            /* didn't converge */
            break;
        }
        term *= -factor;
        sum += term;
        k += 1;
        // `do { ... } while (std::abs(term) > MACHEP * std::abs(sum))`
        if !(term.abs() > MACHEP * sum.abs()) {
            break;
        }
    }
    sum * prefactor
}

