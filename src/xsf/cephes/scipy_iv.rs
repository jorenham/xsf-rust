/*
 * Modified Bessel functions of the first and second kind of fractional order
 *
 * Calculate K(v, x) and K(v+1, x) by method analogous to
 * Temme, Journal of Computational Physics, vol 21, 343 (1976)
 */
#[allow(clippy::cast_precision_loss, clippy::many_single_char_names)]
fn temme_ik_series(v: f64, x: f64) -> (f64, f64) {
    /*
     * |x| <= 2, Temme series converge rapidly
     * |x| > 2, the larger the |x|, the slower the convergence
     */

    let gp = gamma(v + 1.0) - 1.0;
    let gm = gamma(-v + 1.0) - 1.0;

    let a = (x / 2.0).ln();
    let b = (v * a).exp();
    let sigma = -a * v;
    let c = if v.abs() < MACHEP {
        1.0
    } else {
        sinpi(v) / (v * PI)
    };
    let d = if sigma.abs() < MACHEP {
        1.0
    } else {
        sigma.sinh() / sigma
    };
    let gamma1 = if v.abs() < MACHEP {
        -SCIPY_EULER
    } else {
        (0.5 / v) * (gp - gm) * c
    };
    let gamma2 = (2.0 + gp + gm) * c / 2.0;

    /* initial values */
    let mut p = (gp + 1.0) / (2.0 * b);
    let mut q = (1.0 + gm) * b / 2.0;
    let mut f = (sigma.cosh() * gamma1 + d * (-a) * gamma2) / c;
    let mut h = p;
    let mut coef = 1.0;
    let mut sum = coef * f;
    let mut sum1 = coef * h;

    /* series summation */
    let tolerance = MACHEP;
    for k in 1..MAXITER {
        f = (k as f64 * f + p + q) / ((k * k) as f64 - v * v);
        p /= k as f64 - v;
        q /= k as f64 + v;
        h = p - k as f64 * f;
        coef *= x * x / (4 * k) as f64;
        sum += coef * f;
        sum1 += coef * h;
        if (coef * f).abs() < sum.abs() * tolerance {
            break;
        }
    }

    (sum, 2.0 * sum1 / x)
}

/* Evaluate continued fraction fv = I_(v+1) / I_v, derived from
 * Abramowitz and Stegun, Handbook of Mathematical Functions, 1972, 9.1.73 */
#[allow(clippy::cast_precision_loss, clippy::float_cmp, non_snake_case)]
fn CF1_ik(v: f64, x: f64) -> f64 {
    let mut C;
    let mut D;
    let mut f;
    let mut a;
    let mut b;
    let mut delta;

    /*
     * |x| <= |v|, CF1_ik converges rapidly
     * |x| > |v|, CF1_ik needs O(|x|) iterations to converge
     */

    /*
     * modified Lentz's method, see
     * Lentz, Applied Optics, vol 15, 668 (1976)
     */
    let tolerance = 2.0 * MACHEP;
    let tiny = 1.0 / f64::MAX.sqrt();
    C = tiny; /* b0 = 0, replace with tiny */
    f = tiny;
    D = 0.0;
    for k in 1..MAXITER {
        a = 1.0;
        b = 2.0 * (v + k as f64) / x;
        C = b + a / C;
        D = b + a * D;
        if C == 0.0 {
            C = tiny;
        }
        if D == 0.0 {
            D = tiny;
        }
        D = 1.0 / D;
        delta = C * D;
        f *= delta;
        if (delta - 1.0).abs() <= tolerance {
            break;
        }
    }

    f
}

/*
 * Calculate K(v, x) and K(v+1, x) by evaluating continued fraction
 * z1 / z0 = U(v+1.5, 2v+1, 2x) / U(v+0.5, 2v+1, 2x), see
 * Thompson and Barnett, Computer Physics Communications, vol 47, 245 (1987)
 */
#[allow(
    clippy::cast_precision_loss,
    clippy::many_single_char_names,
    non_snake_case
)]
fn CF2_ik(v: f64, x: f64) -> (f64, f64) {
    let mut q;

    /*
     * |x| >= |v|, CF2_ik converges rapidly
     * |x| -> 0, CF2_ik fails to converge
     */

    /*
     * Steed's algorithm, see Thompson and Barnett,
     * Journal of Computational Physics, vol 64, 490 (1986)
     */
    let tolerance = MACHEP;
    let mut a = v * v - 0.25;
    let mut b = 2.0 * (x + 1.0); /* b1 */
    let mut D = 1.0 / b; /* D1 = 1 / b1 */
    let mut delta = D; /* f1 = delta1 = D1, coincidence */
    let mut f = delta;
    let mut prev = 0.0; /* q0 */
    let mut current = 1.0; /* q1 */
    let mut C = -a; /* Q1 = C1 because q1 = 1 */
    let mut Q = C;
    let mut S = 1.0 + Q * delta; /* S1 */
    for k in 2..MAXITER {
        /* starting from 2 */
        /* continued fraction f = z1 / z0 */
        a -= (2 * (k - 1)) as f64;
        b += 2.0;
        D = 1.0 / (b + a * D);
        delta *= b * D - 1.0;
        f += delta;

        /* series summation S = 1 + \sum_{n=1}^{\infty} C_n * z_n / z_0 */
        q = (prev - (b - 2.0) * current) / a;
        prev = current;
        current = q; /* forward recurrence for q */
        C *= -a / k as f64;
        Q += C * q;
        S += Q * delta;

        /* S converges slower than f */
        if (Q * delta).abs() < S.abs() * tolerance {
            break;
        }
    }

    let Kv = (PI / (2.0 * x)).sqrt() * (-x).exp() / S;
    let Kv1 = Kv * (0.5 + v + x + (v * v - 0.25) * f) / x;

    (Kv, Kv1)
}

/* Flags for what to compute */
const IKV_TEMME_NEED_I: i32 = 0x1;
const IKV_TEMME_NEED_K: i32 = 0x2;

/*
 * Compute I(v, x) and K(v, x) simultaneously by Temme's method, see
 * Temme, Journal of Computational Physics, vol 19, 324 (1975)
 */
#[allow(
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    clippy::float_cmp,
    non_snake_case
)]
fn ikv_temme(mut v: f64, x: f64, Iv_p: Option<&mut f64>, Kv_p: Option<&mut f64>) {
    /* Kv1 = K_(v+1), fv = I_(v+1) / I_v */
    /* Ku1 = K_(u+1), fu = I_(u+1) / I_u */
    let mut Iv;
    let Kv;
    let mut reflect = false;

    let mut kind = 0;
    if Iv_p.is_some() {
        kind |= IKV_TEMME_NEED_I;
    }
    if Kv_p.is_some() {
        kind |= IKV_TEMME_NEED_K;
    }

    if v < 0.0 {
        reflect = true;
        v = -v; /* v is non-negative from here */
        kind |= IKV_TEMME_NEED_K;
    }
    let n = v.round() as u32;
    let u = v - f64::from(n); /* -1/2 <= u < 1/2 */

    if x < 0.0 {
        if let Some(Iv_p) = Iv_p {
            *Iv_p = f64::NAN;
        }
        if let Some(Kv_p) = Kv_p {
            *Kv_p = f64::NAN;
        }
        return;
    }
    if x == 0.0 {
        Iv = if v == 0.0 { 1.0 } else { 0.0 };
        if kind & IKV_TEMME_NEED_K != 0 {
            Kv = f64::INFINITY;
        } else {
            Kv = f64::NAN; /* any value will do */
        }

        if reflect && (kind & IKV_TEMME_NEED_I != 0) {
            let z = u + f64::from(n % 2);

            Iv = if sinpi(z) == 0.0 { Iv } else { f64::INFINITY };
        }

        if let Some(Iv_p) = Iv_p {
            *Iv_p = Iv;
        }
        if let Some(Kv_p) = Kv_p {
            *Kv_p = Kv;
        }
        return;
    }
    /* x is positive until reflection */
    let W = 1.0 / x; /* Wronskian */
    let (Ku, Ku1) = if x <= 2.0 {
        /* x in (0, 2] */
        temme_ik_series(u, x) /* Temme series */
    } else {
        /* x in (2, \infty) */
        CF2_ik(u, x) /* continued fraction CF2_ik */
    };
    let mut prev = Ku;
    let mut current = Ku1;
    for k in 1..=n {
        /* forward recurrence for K */
        let next = 2.0 * (u + f64::from(k)) * current / x + prev;
        prev = current;
        current = next;
    }
    Kv = prev;
    let Kv1 = current;
    if kind & IKV_TEMME_NEED_I != 0 {
        let mut lim = (4.0 * v * v + 10.0) / (8.0 * x);

        lim *= lim;
        lim *= lim;
        lim /= 24.0;
        if (lim < MACHEP * 10.0) && (x > 100.0) {
            /*
             * x is huge compared to v, CF1 may be very slow
             * to converge so use asymptotic expansion for large
             * x case instead.  Note that the asymptotic expansion
             * isn't very accurate - so it's deliberately very hard
             * to get here - probably we're going to overflow:
             */
            Iv = iv_asymptotic(v, x);
        } else {
            let fv = CF1_ik(v, x); /* continued fraction CF1_ik */
            Iv = W / (Kv * fv + Kv1); /* Wronskian relation */
        }
    } else {
        Iv = f64::NAN; /* any value will do */
    }

    if reflect {
        let z = u + f64::from(n % 2);

        if let Some(Iv_p) = Iv_p {
            *Iv_p = Iv + (2.0 / PI) * sinpi(z) * Kv; /* reflection formula */
        }
        if let Some(Kv_p) = Kv_p {
            *Kv_p = Kv;
        }
    } else {
        if let Some(Iv_p) = Iv_p {
            *Iv_p = Iv;
        }
        if let Some(Kv_p) = Kv_p {
            *Kv_p = Kv;
        }
    }
}

/// Modified Bessel function of noninteger order
///
/// Returns modified Bessel function of order v of the
/// argument.  If x is negative, v must be integer valued.
#[allow(clippy::float_cmp)]
pub(crate) fn iv(mut v: f64, x: f64) -> f64 {
    let mut res = 0.0;

    if v.is_nan() || x.is_nan() {
        return f64::NAN;
    }

    /* If v is a negative integer, invoke symmetry */
    let mut t = v.floor();
    if v < 0.0 && t == v {
        v = -v; /* symmetry */
        t = -t;
    }
    /* If x is negative, require v to be an integer */
    let mut sign = 1.0;
    if x < 0.0 {
        if t != v {
            return f64::NAN;
        }
        if v != 2.0 * (v / 2.0).floor() {
            sign = -1.0;
        }
    }

    /* Avoid logarithm singularity */
    if x == 0.0 {
        if v == 0.0 {
            return 1.0;
        }
        if v < 0.0 {
            return f64::INFINITY;
        }
        return 0.0;
    }

    let ax = x.abs();
    if v.abs() > 50.0 {
        /*
         * Uniform asymptotic expansion for large orders.
         *
         * This appears to overflow slightly later than the Boost
         * implementation of Temme's method.
         */
        ikv_asymptotic_uniform(v, ax, Some(&mut res), None);
    } else {
        /* Otherwise: Temme's method */
        ikv_temme(v, ax, Some(&mut res), None);
    }
    res *= sign;
    res
}
