/*
 * Compute Iv, Kv from (AMS5 9.7.7 + 9.7.8), asymptotic expansion for large v
 */
#[allow(clippy::needless_range_loop, clippy::similar_names)]
fn ikv_asymptotic_uniform(
    mut v: f64,
    x: f64,
    i_value: Option<&mut f64>,
    k_value: Option<&mut f64>,
) {
    let mut sign = 1;

    if v < 0.0 {
        /* Negative v; compute I_{-v} and K_{-v} and use (AMS 9.6.2) */
        sign = -1;
        v = -v;
    }

    let z = x / v;
    let t = 1.0 / (1.0 + z * z).sqrt();
    let t2 = t * t;
    let eta = (1.0 + z * z).sqrt() + (z / (1.0 + 1.0 / t)).ln();

    let i_prefactor = (t / (2.0 * PI * v)).sqrt() * (v * eta).exp();
    let mut i_sum = 1.0;

    let k_prefactor = (PI * t / (2.0 * v)).sqrt() * (-v * eta).exp();
    let mut k_sum = 1.0;

    let mut divisor = v;
    for n in 1..IV_N_UFACTORS {
        /*
         * Evaluate u_k(t) with Horner's scheme;
         * (using the knowledge about which coefficients are zero)
         */
        let mut term = 0.0;
        for k in (IV_N_UFACTOR_TERMS - 1 - 3 * n..IV_N_UFACTOR_TERMS - n).step_by(2) {
            term *= t2;
            term += IV_ASYMPTOTIC_UFACTORS[n][k];
        }
        for _ in (1..n).step_by(2) {
            term *= t2;
        }
        if n % 2 == 1 {
            term *= t;
        }

        /* Sum terms */
        term /= divisor;
        i_sum += term;
        k_sum += if n % 2 == 0 { term } else { -term };

        /* Check convergence */
        if term.abs() < MACHEP {
            break;
        }

        divisor *= v;
    }

    if let Some(k_value) = k_value {
        /* symmetric in v */
        *k_value = k_prefactor * k_sum;
    }

    if let Some(i_value) = i_value {
        if sign == 1 {
            *i_value = i_prefactor * i_sum;
        } else {
            /* (AMS 9.6.2) */
            *i_value = i_prefactor * i_sum + (2.0 / PI) * sinpi(v) * k_prefactor * k_sum;
        }
    }
}

