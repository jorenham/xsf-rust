#[allow(
    clippy::too_many_arguments,
    clippy::cast_possible_truncation,
    clippy::approx_constant
)]
#[allow(clippy::excessive_precision)]
pub(crate) fn acai(
    z: Complex64,
    fnu: f64,
    kode: i32,
    mr: i32,
    n: i32,
    y: &mut [Complex64],
    rl: f64,
    tol: f64,
    elim: f64,
    alim: f64,
) -> i32 {
    //***BEGIN PROLOGUE  ZACAI
    //***REFER TO  ZAIRY
    //
    //     ZACAI APPLIES THE ANALYTIC CONTINUATION FORMULA
    //
    //         K(FNU,ZN*EXP(MP))=K(FNU,ZN)*EXP(-MP*FNU) - MP*I(FNU,ZN)
    //                 MP=PI*MR*std::complex<double>(0.0,1.0)
    //
    //     TO CONTINUE THE K FUNCTION FROM THE RIGHT HALF TO THE LEFT
    //     HALF Z PLANE FOR USE WITH ZAIRY WHERE FNU=1/3 OR 2/3 AND N=1.
    //     ZACAI IS THE SAME AS ZACON WITH THE PARTS FOR LARGER ORDERS AND
    //     RECURRENCE REMOVED. A RECURSIVE CALL TO ZACON CAN RESULT IF ZACON
    //     IS CALLED FROM ZAIRY.
    //
    //***ROUTINES CALLED  ZASYI,ZBKNU,ZMLRI,ZSERI,ZS1S2,D1MACH,AZABS
    //***END PROLOGUE  ZACAI

    let mut cy = [Complex64::ZERO; 2];
    let mut cpn: f64;
    let mut spn: f64;
    let mut nw: i32;
    let pi: f64 = 3.14159265358979324;
    let mut nz: i32 = 0;
    let zn = -z;
    let az = z.norm();
    let nn = n;
    let dfnu = fnu + f64::from(n - 1);
    if (az > 2.0) && (az * az * 0.25 > dfnu + 1.0) {
        /* 20 */
        if az >= rl {
            //
            // ASYMPTOTIC EXPANSION FOR LARGE Z FOR THE I FUNCTION
            //
            nw = asyi(zn, fnu, kode, nn, y, rl, tol, elim, alim);
        } else {
            //
            // MILLER ALGORITHM NORMALIZED BY THE SERIES FOR THE I FUNCTION
            //
            nw = mlri(zn, fnu, kode, nn, y, tol);
        }
        if nw < 0 {
            nz = -1;
            if nw == -2 {
                nz = -2;
            }
            return nz;
        }
    } else {
        //
        // POWER SERIES FOR THE I FUNCTION
        //
        seri(zn, fnu, kode, nn, y, tol, elim, alim);
    }
    /* 40 */
    //
    // ANALYTIC CONTINUATION TO THE LEFT HALF PLANE FOR THE K FUNCTION
    //
    nw = bknu(zn, fnu, kode, 1, &mut cy, tol, elim, alim);
    if nw != 0 {
        nz = -1;
        if nw == -2 {
            nz = -2;
        }
        return nz;
    }
    let fmr = f64::from(mr);
    let sgn = if fmr < 0.0 { pi } else { -pi };
    let mut csgn = c64(0.0, sgn);
    if kode != 1 {
        let yy = -zn.im;
        cpn = yy.cos();
        spn = yy.sin();
        csgn = cmul(csgn, c64(cpn, spn));
    }
    //
    // CALCULATE CSPN=EXP(FNU*PI*I) TO MINIMIZE LOSSES OF SIGNIFICANCE
    // WHEN FNU IS LARGE
    //
    let inu = fnu as i32;
    let arg = (fnu - f64::from(inu)) * sgn;
    cpn = arg.cos();
    spn = arg.sin();
    let mut cspn = c64(cpn, spn);
    if inu % 2 == 1 {
        cspn = -cspn;
    }
    let mut c1 = cy[0];
    let mut c2 = y[0];
    if kode != 1 {
        let mut iuf = 0;
        let ascle = 1e3 * D1MACH[0] / tol;
        nw = s1s2(zn, &mut c1, &mut c2, ascle, alim, &mut iuf);
        nz += nw;
    }
    y[0] = cmul(cspn, c1) + cmul(csgn, c2);
    nz
}

