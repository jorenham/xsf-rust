/// `(s, e)` with `s = fl(a + b)` and `s + e = a + b` exactly, for `|a| >= |b|`
#[inline]
fn fast_two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    (s, b - (s - a))
}

/// `x` without its low `SPLIT_BITS` bits: this has at most 24 bits, and `x - head(x)` is exact
#[inline]
fn head(x: f64) -> f64 {
    f64::from_bits(x.to_bits() & (u64::MAX << SPLIT_BITS))
}

/// `r^3 P(r)`
#[inline]
fn log1p_tail(r: f64) -> f64 {
    let r2 = r * r;
    let p =
        ((P[0] + r * P[1]) + r2 * (P[2] + r * P[3])) + (r2 * r2) * ((P[4] + r * P[5]) + r2 * P[6]);
    r * r2 * p
}

/// Natural logarithm of `1 + x`
pub(crate) fn log1p(x: f64) -> f64 {
    let u = 1.0 + x;
    // u = 2^k m with m in [OFF, 2 OFF), which is split in intervals of equal bit patterns
    let tmp = u.to_bits().wrapping_sub(OFF);

    if tmp >> INDEX_SHIFT == I_ONE {
        // k = 0 and invc = 1: no reduction
        if x.abs() < const { pow2(-54) } {
            // x is the nearest f64, and this keeps the sign of zero
            return x;
        }
        // x - x^2 / 2 = hi + e - (x + xh) xl / 2, since xh^2 is exact
        let xh = head(x);
        let xl = x - xh;
        let (hi, e) = fast_two_sum(x, -0.5 * xh * xh);
        return hi + ((e - 0.5 * (x + xh) * xl) + log1p_tail(x));
    }
    if !(x > -1.0 && x < f64::INFINITY) {
        return if x == -1.0 {
            f64::NEG_INFINITY
        } else if x < -1.0 {
            f64::NAN
        } else {
            // +inf or NaN
            x
        };
    }

    // the bits of tmp above the mantissa are k, as a signed integer
    let k = ((tmp >> u32::BITS) as i32) >> (MANTISSA_BITS - u32::BITS);
    let (invc, logc_hi, logc_lo) = TABLE[(tmp >> INDEX_SHIFT) as usize % TABLE.len()];
    let m = f64::from_bits(u.to_bits().wrapping_sub(tmp & EXPONENT_MASK));
    // 1 + x = u + c exactly, and c 2^-k corrects m, which is negligible for k > K_MAX
    let (a, b) = if x < 1.0 { (1.0, x) } else { (x, 1.0) };
    let c = (b - (u - a)) * pow2(-k.min(K_MAX));

    // 1 + x = 2^k (1 + r) / invc with r = rh + rl, where rh is exact and a multiple of 2^-33:
    // mh has at most 24 bits, and invc is a multiple of 2^-9
    let mh = head(m);
    let rh = mh * invc - 1.0;
    let rl = ((m - mh) + c) * invc;

    // log1p(x) = k ln(2) - ln(invc) + r - r^2 / 2 + r^3 P(r)
    //
    // s is exact, as LN2_HI and logc_hi are multiples of 2^-42, and rh^2 as rh has at most 26 bits
    let kd = f64::from(k);
    let s = (kd * LN2_HI + logc_hi) + rh;
    let (hi, e) = fast_two_sum(s, -0.5 * rh * rh);
    let lo = (rl + (kd * LN2_LO + logc_lo)) - rl * (rh + 0.5 * rl);
    hi + ((e + lo) + log1p_tail(rh + rl))
}
