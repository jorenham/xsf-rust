//! The real `log1p`, with an error below 0.501 ulp, and without FMA.
//!
//! The method is that of the fast path of `log1p` in CORE-MATH (`src/binary64/log1p/log1p.c`): a
//! polynomial near zero, and otherwise a table of reciprocals `invc` with `-ln(invc)` in
//! double-double. Here `invc` is a multiple of 2^-9, so that the reduced argument is exact after
//! splitting `m`. The decomposition of `1 + x` into `2^k m` and a table index is that of `log` in
//! the ARM Optimized Routines (`math/log.c`).
