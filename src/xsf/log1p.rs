/// The sign and exponent bits of an `f64`
const EXPONENT_MASK: u64 = u64::MAX << MANTISSA_BITS;
/// Number of low bits of an `f64` that are not in its `head`
const SPLIT_BITS: u32 = 29;
/// Position of the table index in the bits of an `f64`
const INDEX_SHIFT: u32 = MANTISSA_BITS - TABLE.len().ilog2();
/// Largest `k` for which `2^-k` is a normal `f64`
const K_MAX: i32 = 1 - f64::MIN_EXP;

/// Bits of the lower bound of `m`, about 0.707; `1` is then inside of an interval
