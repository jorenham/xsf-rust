fn cpp_signatures(cpp: &str) -> impl Iterator<Item = &str> {
    cpp.lines().map(|line| line.trim_end()).filter_map(|line| {
        if !line.starts_with(' ') && line.contains('(') && line.ends_with(r") {") {
            Some(line[..line.len() - 2].trim_end())
        } else {
            None
        }
    })
}

fn get_ctype(code: char) -> &'static str {
    match code {
        'i' => "int",
        'l' => "long",
        'd' => "double",
        'D' => "c_complex",
        _ => panic!("Unknown parameter type"),
    }
}

fn split_typespec(spec: &str) -> (&str, &str) {
    spec.split_once("->").unwrap()
}

fn fmt_return(spec: &str) -> &str {
    let chars = split_typespec(spec).1;
    if chars.len() > 1 {
        "void"
    } else {
        get_ctype(chars.chars().next().unwrap())
    }
}

fn fmt_params(spec: &str) -> String {
    let (inputs, outputs) = split_typespec(spec);

    let mut params = inputs
        .chars()
        .map(get_ctype)
        .enumerate()
        .map(|(i, ct)| format!("{ct} x{i}"))
        .collect::<Vec<_>>();

    if outputs.len() > 1 {
        params.extend(
            outputs
                .chars()
                .map(get_ctype)
                .enumerate()
                .map(|(i, ct)| format!("{ct} &y{i}")),
        );
    }

    params.join(", ")
}

fn fmt_func(name: &str, spec: &str, suffix: &str) -> String {
    let rtype = fmt_return(spec);
    let params = fmt_params(spec);

    let fname = if suffix.is_empty() {
        name.to_string()
    } else {
        format!("{name}_{suffix}")
    };
    format!("{rtype} {fname}({params})")
}

fn wrapper_decls() -> impl Iterator<Item = (&'static str, &'static str, String)> {
    let mut name_counts = HashMap::new();
    WRAPPER_SPECS.iter().map(move |&(name, spec)| {
        let count = name_counts.entry(name).or_insert(0);
        let suffix = if *count == 0 {
            String::new()
        } else {
            count.to_string()
        };
        *count += 1;
        (name, spec, fmt_func(name, spec, &suffix))
    })
}

fn fmt_call(name: &str, spec: &str) -> String {
    let (inputs, outputs) = split_typespec(spec);

    let mut args = inputs
        .chars()
        .enumerate()
        .map(|(i, c)| {
            if c == 'D' {
                format!("to_cpp_complex(x{i})")
            } else {
                format!("x{i}")
            }
        })
        .collect::<Vec<String>>();

    if outputs.len() > 1 {
        args.extend(outputs.chars().enumerate().map(|(i, c)| {
            if c == 'D' {
                format!("as_cpp_complex(y{i})")
            } else {
                format!("y{i}")
            }
        }));
    }

    let call = format!("xsf::{name}({})", args.join(", "));
    match outputs {
        "D" => format!("return to_c_complex({call})"),
        _ if outputs.len() == 1 => format!("return {call}"),
        _ => call,
    }
}

fn push_line(source: &mut String, line: &str) {
    source.push_str(line.trim_end());
    source.push('\n');
}

fn write_file(path: String, content: String) -> String {
    fs::write(&path, content).unwrap();
    path
}

fn generate_hpp(dir_out: &str) -> String {
    let mut source = String::from(WRAPPER_PREAMBLE);

    // includes
    push_line(&mut source, "#include <complex>");
    push_line(&mut source, "");

    // namespace
    push_line(&mut source, &format!("namespace {WRAPPER_NAME} {{"));

    // complex helpers
    push_line(&mut source, CPP_COMPLEX_HELPERS);

    // simple wrappers
    for (_, _, decl) in wrapper_decls() {
        push_line(&mut source, &format!("{decl};"));
    }

    // additional wrappers
    for sig in cpp_signatures(CPP_WRAPPERS) {
        push_line(&mut source, &format!("{sig};"));
    }

    // close namespace
    push_line(&mut source, "}");

    // write to file
    write_file(format!("{dir_out}/{WRAPPER_NAME}.hpp"), source)
}

fn generate_cpp(dir_out: &str) -> String {
    let mut source = String::from(WRAPPER_PREAMBLE);

    // C++23 `std::mdspan` backport
    push_line(&mut source, "#define MDSPAN_USE_PAREN_OPERATOR 1");
    push_line(
        &mut source,
        r#"#include "xsf/third_party/kokkos/mdspan.hpp""#,
    );
    push_line(&mut source, "");

    // includes
    push_line(&mut source, &format!(r#"#include "{WRAPPER_NAME}.hpp""#));
    for xsf_header in WRAPPER_INCLUDES {
        push_line(&mut source, &format!(r#"#include "xsf/{xsf_header}""#));
    }
    push_line(&mut source, "");

    // namespace
    push_line(&mut source, &format!("namespace {WRAPPER_NAME} {{"));
    push_line(&mut source, "");

    // simple wrappers
    for (name, spec, decl) in wrapper_decls() {
        push_line(&mut source, &format!("{decl} {{"));
        push_line(&mut source, &format!("    {};", fmt_call(name, spec)));
        push_line(&mut source, "}");
    }

    // additional wrappers
    push_line(&mut source, CPP_WRAPPERS);

    // close namespace
    push_line(&mut source, "");
    push_line(&mut source, "}");

    // write to file
    write_file(format!("{dir_out}/{WRAPPER_NAME}.cpp"), source)
}

fn build_wrapper(dir_out: &str) {
    let file_cpp = generate_cpp(dir_out);

    cc::Build::new()
        .cpp(true)
        .std(CXX_STANDARD)
        .flag_if_supported("-Wno-unused-parameter")
        .flag_if_supported("-Wno-logical-op-parentheses")
        .include(xsf_include())
        .file(file_cpp)
        .compile(WRAPPER_NAME)
}

fn get_allowlist() -> String {
    format!(
        "{}::({})",
        WRAPPER_NAME,
        WRAPPER_SPECS
            .iter()
            .map(|(name, _)| format!(r"{name}(_\d)?"))
            .chain(cpp_signatures(CPP_WRAPPERS).filter_map(|sig| {
                sig.split('(')
                    .next()?
                    .split_whitespace()
                    .last()
                    .map(String::from)
            }))
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect::<Vec<_>>()
            .join("|")
    )
}

fn generate_bindings(dir_out: &str, header: &str) {
    bindgen::Builder::default()
        .header(header)
        .allowlist_function(get_allowlist())
        .blocklist_type("xsf_wrapper::c_complex")
        .clang_args(["-x", "c++", "-DBINDGEN"])
        .enable_cxx_namespaces()
        .sort_semantically(true)
        .merge_extern_blocks(true)
        .use_core()
        .module_raw_line(
            "root::xsf_wrapper",
            "pub type c_complex = num_complex::Complex<f64>;",
        )
        // The header being generated by us, we don't want its mtime to be taken into account to
        // rerun this script, it should be always the same output for a given version of the crate
        // So disable the rerun_on_header_files for the callbacks
        .parse_callbacks(Box::new(bindgen::CargoCallbacks::new().rerun_on_header_files(false)))
        .generate()
        .unwrap()
        .write_to_file(PathBuf::from(dir_out).join("bindings.rs"))
        .unwrap();
}

fn main() {
    let out_dir = env::var("OUT_DIR").unwrap();
    let header = generate_hpp(&out_dir);

    println!("cargo:rerun-if-changed={}", xsf_include());

    build_wrapper(&out_dir);
    generate_bindings(&out_dir, &header);
}
