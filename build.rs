/// Top-level signatures of the hand-written `CPP_WRAPPERS`, e.g. `double xsfr_poch(double a, double m)`
fn cpp_signatures(cpp: &str) -> impl Iterator<Item = &str> {
    cpp.lines().map(str::trim_end).filter_map(|line| {
        if line.is_empty() || line.starts_with([' ', '}']) || line.starts_with("//") {
            None
        } else {
            Some(
                line.strip_suffix(" {").unwrap_or_else(|| {
                    panic!("unexpected top-level line in CPP_WRAPPERS: {line:?}")
                }),
            )
        }
    })
}

fn get_ctype(code: char) -> &'static str {
    match code {
        'i' => "int",
        'l' => "long",
        'd' => "double",
        'D' => "c_complex",
        _ => panic!("Unknown parameter type"),
    }
}

fn split_typespec(spec: &str) -> (&str, &str) {
    spec.split_once("->").unwrap()
}

fn fmt_return(spec: &str) -> &str {
    let chars = split_typespec(spec).1;
    if chars.len() > 1 {
        "void"
    } else {
        get_ctype(chars.chars().next().unwrap())
    }
}

fn fmt_params(spec: &str) -> String {
    let (inputs, outputs) = split_typespec(spec);

    let mut params = inputs
        .chars()
        .map(get_ctype)
        .enumerate()
        .map(|(i, ct)| format!("{ct} x{i}"))
        .collect::<Vec<_>>();

    if outputs.len() > 1 {
        params.extend(
            outputs
                .chars()
                .map(get_ctype)
                .enumerate()
                .map(|(i, ct)| format!("{ct} &y{i}")),
        );
    }

    params.join(", ")
}

fn fmt_func(name: &str, spec: &str, suffix: &str) -> String {
    let rtype = fmt_return(spec);
    let params = fmt_params(spec);

    let fname = if suffix.is_empty() {
        name.to_string()
    } else {
        format!("{name}_{suffix}")
    };
    format!("{rtype} {WRAPPER_PREFIX}{fname}({params})")
}

fn wrapper_decls() -> impl Iterator<Item = (&'static str, &'static str, String)> {
    let mut name_counts = HashMap::new();
    WRAPPER_SPECS.iter().map(move |&(name, spec)| {
        let count = name_counts.entry(name).or_insert(0);
        let suffix = if *count == 0 {
            String::new()
        } else {
            count.to_string()
        };
        *count += 1;
        (name, spec, fmt_func(name, spec, &suffix))
    })
}

fn fmt_call(name: &str, spec: &str) -> String {
    let (inputs, outputs) = split_typespec(spec);

    let mut args = inputs
        .chars()
        .enumerate()
        .map(|(i, c)| {
            if c == 'D' {
                format!("to_cpp_complex(x{i})")
            } else {
                format!("x{i}")
            }
        })
        .collect::<Vec<String>>();

    if outputs.len() > 1 {
        args.extend(outputs.chars().enumerate().map(|(i, c)| {
            if c == 'D' {
                format!("as_cpp_complex(y{i})")
            } else {
                format!("y{i}")
            }
        }));
    }

    let call = format!("xsf::{name}({})", args.join(", "));
    match outputs {
        "D" => format!("return to_c_complex({call})"),
        _ if outputs.len() == 1 => format!("return {call}"),
        _ => call,
    }
}

fn push_line(source: &mut String, line: &str) {
    source.push_str(line.trim_end());
    source.push('\n');
}

fn write_file(path: String, content: String) -> String {
    fs::write(&path, content).unwrap();
    path
}

fn generate_cpp(dir_out: &str) -> String {
    let mut source = String::from(WRAPPER_PREAMBLE);

    // C++23 `std::mdspan` backport
    push_line(&mut source, "#define MDSPAN_USE_PAREN_OPERATOR 1");
    push_line(
        &mut source,
        r#"#include "xsf/third_party/kokkos/mdspan.hpp""#,
    );
    push_line(&mut source, "");

    // includes
    push_line(&mut source, "#include <complex>");
    for xsf_header in WRAPPER_INCLUDES {
        push_line(&mut source, &format!(r#"#include "xsf/{xsf_header}""#));
    }

    // complex helpers
    push_line(&mut source, CPP_COMPLEX_HELPERS);

    // C linkage
    push_line(&mut source, r#"extern "C" {"#);
    push_line(&mut source, "");

    // simple wrappers
    for (name, spec, decl) in wrapper_decls() {
        push_line(&mut source, &format!("{decl} {{"));
        push_line(&mut source, &format!("    {};", fmt_call(name, spec)));
        push_line(&mut source, "}");
    }

    // additional wrappers
    push_line(&mut source, CPP_WRAPPERS);

    // close C linkage
    push_line(&mut source, "");
    push_line(&mut source, "}");

    // write to file
    write_file(format!("{dir_out}/{WRAPPER_NAME}.cpp"), source)
}

fn build_wrapper(dir_out: &str, xsf_include: &str) {
    let file_cpp = generate_cpp(dir_out);

    cc::Build::new()
        .cpp(true)
        .std(CXX_STANDARD)
        .flag_if_supported("-Wno-unused-parameter")
        .flag_if_supported("-Wno-logical-op-parentheses")
        .include(xsf_include)
        .file(file_cpp)
        .compile(WRAPPER_NAME)
}

/// Rust FFI type of a C parameter or return type, e.g. `const double *` -> `*const f64`
fn rust_type(ctype: &str) -> String {
    let ctype = ctype.trim();
    if let Some(pointee) = ctype.strip_suffix(['*', '&']) {
        return match pointee.trim().strip_prefix("const ") {
            Some(pointee) => format!("*const {}", rust_type(pointee)),
            None => format!("*mut {}", rust_type(pointee)),
        };
    }
    match ctype {
        "int" => "core::ffi::c_int",
        "long" => "core::ffi::c_long",
        "double" => "f64",
        "size_t" => "usize",
        "c_complex" => "c_complex",
        _ => panic!("unsupported C type: {ctype:?}"),
    }
    .to_string()
}

fn is_ident(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn unsupported<T>(sig: &str) -> T {
    panic!("unsupported C signature: {sig:?}")
}

/// Rust `extern "C"` declaration of a C signature, e.g. `double xsfr_poch(double a, double m)`
fn fmt_extern(sig: &str) -> (String, String) {
    let (head, params) = sig
        .strip_suffix(')')
        .and_then(|s| s.split_once('('))
        .unwrap_or_else(|| unsupported(sig));
    let (rtype, symbol) = head.rsplit_once(' ').unwrap_or_else(|| unsupported(sig));
    let name = symbol
        .strip_prefix(WRAPPER_PREFIX)
        .filter(|name| is_ident(name))
        .unwrap_or_else(|| unsupported(sig));

    let params = params
        .split(',')
        .map(str::trim)
        .filter(|param| !param.is_empty())
        .map(|param| {
            let i = param
                .rfind([' ', '*', '&'])
                .unwrap_or_else(|| unsupported(sig))
                + 1;
            let (ptype, pname) = param.split_at(i);
            if !is_ident(pname) {
                unsupported::<()>(sig);
            }
            format!("{pname}: {}", rust_type(ptype))
        })
        .collect::<Vec<_>>()
        .join(", ");
    let ret = match rtype.trim() {
        "void" => String::new(),
        rtype => format!(" -> {}", rust_type(rtype)),
    };

    let decl = format!("    #[link_name = \"{symbol}\"]\n    pub fn {name}({params}){ret};\n");
    (name.to_string(), decl)
}

fn generate_bindings(dir_out: &str) {
    let mut source = String::from(WRAPPER_PREAMBLE);
    source.push_str("pub type c_complex = num_complex::Complex<f64>;\n\n");
    source.push_str("unsafe extern \"C\" {\n");

    let mut names = HashSet::new();
    let sigs = wrapper_decls()
        .map(|(_, _, decl)| decl)
        .chain(cpp_signatures(CPP_WRAPPERS).map(String::from));
    for sig in sigs {
        let (name, decl) = fmt_extern(&sig);
        assert!(names.insert(name), "duplicate wrapper: {sig:?}");
        source.push_str(&decl);
    }

    source.push_str("}\n");
    write_file(format!("{dir_out}/bindings.rs"), source);
}

fn main() {
    let out_dir = env::var("OUT_DIR").unwrap();
    let xsf_include = format!("{}/xsf/include", env::var("CARGO_MANIFEST_DIR").unwrap());

    println!("cargo:rerun-if-changed={xsf_include}");

    build_wrapper(&out_dir, &xsf_include);
    generate_bindings(&out_dir);
}
